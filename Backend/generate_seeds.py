def gen_program_messages():
    src = os.path.join(BACKUPS, "2026_02_16_messages_all.csv")
    out = os.path.join(SEEDS, "20_program_messages.sql")
    # 'tutorial' program is NOT in the programs table — omit to avoid FK violation
    valid_programs = {"clear30", "clear30-start-soon", "life"}

    print(f"  Generating {out}...")
    rows_written = 0

    with open(src, newline="", encoding="utf-8") as csvfile, \
         open(out, "w", encoding="utf-8") as f:

        write_header(f, "programs.program_messages", os.path.basename(src))
        # Bypass FK checks during seeding — some guide_ids may not exist in the guides CSV
        f.write("SET session_replication_role = replica;\n\n")
        f.write("TRUNCATE programs.program_messages CASCADE;\n\n")

        reader = csv.DictReader(csvfile)
        for row in reader:
            prog = row.get("program", "").strip()
            # Only import rows belonging to known programs
            if prog not in valid_programs:
                continue

            vals = ", ".join([
                q_int(row.get("id")),
                q_int(row.get("day")),
                q(row.get("title")),
                q(row.get("subtitle")),
                q(row.get("body")),
                q(row.get("program")),
                q(row.get("question_id")),
                q(row.get("question_response")),
                q_json(row.get("resources")),
                q_json(row.get("claire_prompts")),
                q_json(row.get("journal_prompts")),
                q_json(row.get("meditation")),
                q_json(row.get("page_info")),
                q(row.get("stage")),
                q(row.get("guide_id")),
                q(row.get("notification_body")),
                q(row.get("notification_title")),
                q(row.get("thumbnail_url")),
                q(row.get("video_url")),
                q_json(row.get("instagram_videos")),
                q_json(row.get("carousel_images")),
                q_json(row.get("member_perks")),
                q_json(row.get("claire_prompts_json")),
            ])
            f.write(
                f"INSERT INTO programs.program_messages "
                f"(id, day, title, subtitle, body, program, question_id, question_response, "
                f"resources, claire_prompts, journal_prompts, meditation, page_info, stage, "
                f"guide_id, notification_body, notification_title, thumbnail_url, video_url, "
                f"instagram_videos, carousel_images, member_perks, claire_prompts_json) "
                f"VALUES ({vals}) ON CONFLICT (id) DO NOTHING;\n"
            )
            rows_written += 1

        f.write("\nSET session_replication_role = DEFAULT;\n")

    print(f"    ✅ {rows_written} rows")


