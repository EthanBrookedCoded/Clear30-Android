def q(val):
    """SQL-escape a value. Returns NULL for empty, or a properly quoted string."""
    if val is None or val == "":
        return "NULL"
    # Escape single quotes by doubling them
    escaped = str(val).replace("'", "''")
    return f"'{escaped}'"


def q_bool(val):
    """Convert CSV boolean string to SQL boolean."""
    if val is None or val == "":
        return "NULL"
    if str(val).lower() in ("true", "t", "1", "yes"):
        return "TRUE"
    if str(val).lower() in ("false", "f", "0", "no"):
        return "FALSE"
    return "NULL"


def q_int(val):
    """Convert to integer or NULL."""
    if val is None or val == "":
        return "NULL"
    try:
        return str(int(val))
    except (ValueError, TypeError):
        return "NULL"


def q_json(val):
    """Quote a JSON value — validate it's valid JSON, return NULL if empty."""
    if val is None or val == "":
        return "NULL"
    val = str(val).strip()
    if val == "" or val == "null":
        return "NULL"
    # Validate JSON
    try:
        json.loads(val)
    except json.JSONDecodeError:
        # If it's not valid JSON, return NULL rather than crashing
        print(f"  ⚠️  Invalid JSON skipped: {val[:80]}", file=sys.stderr)
        return "NULL"
    escaped = val.replace("'", "''")
    return f"'{escaped}'"


def write_header(f, table, source_csv):
    f.write(f"-- Seed: {table}\n")
    f.write(f"-- Source: {source_csv}\n")
    f.write(f"-- Generated by generate_seeds.py\n\n")


