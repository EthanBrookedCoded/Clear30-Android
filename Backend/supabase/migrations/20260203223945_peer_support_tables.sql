-- Peer Support Migration: SMS to In-App Messaging
-- Part 1: Tables, Functions, Triggers, and Indexes

--------------------------------------------------------------------------------
-- 1. NEW TABLES
--------------------------------------------------------------------------------

-- comms.peer_messages - Core storage for in-app messages
CREATE TABLE comms.peer_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    text TEXT NOT NULL,
    outbound BOOLEAN NOT NULL DEFAULT false,  -- true = from admin/system
    type TEXT DEFAULT 'manual',  -- 'manual', 'milestone', 'system', 'migrated'
    template_id BIGINT,  -- references library.peer_day.id if from template
    read_at TIMESTAMPTZ,
    notification_sent TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted BOOLEAN NOT NULL DEFAULT false
);

-- Index for efficient user message queries
CREATE INDEX idx_peer_messages_user_id ON comms.peer_messages(user_id, created_at DESC);

-- Index for push notification processing
CREATE INDEX idx_peer_messages_notification ON comms.peer_messages(outbound, notification_sent)
    WHERE outbound = true AND notification_sent IS NULL;

-- Enable realtime
ALTER PUBLICATION supabase_realtime ADD TABLE comms.peer_messages;

-- comms.peer_conversations - Denormalized view for admin panel
CREATE TABLE comms.peer_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT,
    last_message_id BIGINT,
    last_message_text TEXT,
    last_message_timestamp TIMESTAMPTZ,
    last_message_outbound BOOLEAN,
    unread_count INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Index for admin panel sorting
CREATE INDEX idx_peer_conversations_updated ON comms.peer_conversations(updated_at DESC);

-- library.peer_day - In-app message templates (separate from sms_day)
CREATE TABLE library.peer_day (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day INT NOT NULL,  -- day in program (0, 10, 30, etc.)
    program TEXT NOT NULL DEFAULT 'clear30',  -- 'clear30', 'life'
    text TEXT NOT NULL,  -- message template with _CLIENTNAME_ etc.
    question_id TEXT,  -- assessment question to condition on
    question_response TEXT,  -- expected response value
    variant_id TEXT,  -- e.g., 'x10-day-perfect', 'breakdown-good'
    variant_conditions JSONB,  -- e.g., {"check_in_count": {"min": 7, "max": 9}}
    hour_utc INT DEFAULT 16,  -- hour to send (UTC), default 4 PM
    active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now()
);

-- Index for efficient lookup
CREATE INDEX idx_peer_day_lookup ON library.peer_day(day, program, active);

