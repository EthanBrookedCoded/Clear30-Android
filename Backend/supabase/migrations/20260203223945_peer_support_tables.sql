--------------------------------------------------------------------------------
-- 6. RLS POLICIES
--------------------------------------------------------------------------------

-- Enable RLS
ALTER TABLE comms.peer_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE comms.peer_conversations ENABLE ROW LEVEL SECURITY;
ALTER TABLE library.peer_day ENABLE ROW LEVEL SECURITY;

-- peer_messages: Users can read/write their own messages
CREATE POLICY "Users can read own peer messages" ON comms.peer_messages
    FOR SELECT USING (user_id = auth.uid()::text OR auth.role() = 'service_role');

CREATE POLICY "Users can insert own peer messages" ON comms.peer_messages
    FOR INSERT WITH CHECK (user_id = auth.uid()::text OR auth.role() = 'service_role');

CREATE POLICY "Service role can update peer messages" ON comms.peer_messages
    FOR UPDATE USING (auth.role() = 'service_role');

-- peer_conversations: Users can read their own conversation
CREATE POLICY "Users can read own peer conversation" ON comms.peer_conversations
    FOR SELECT USING (user_id = auth.uid()::text OR auth.role() = 'service_role');

CREATE POLICY "Service role can manage peer conversations" ON comms.peer_conversations
    FOR ALL USING (auth.role() = 'service_role');

-- peer_day: All authenticated users can read templates
CREATE POLICY "Authenticated users can read peer_day" ON library.peer_day
    FOR SELECT USING (auth.role() = 'authenticated' OR auth.role() = 'service_role');

CREATE POLICY "Service role can manage peer_day" ON library.peer_day
    FOR ALL USING (auth.role() = 'service_role');
