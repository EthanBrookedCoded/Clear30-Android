--------------------------------------------------------------------------------

ALTER TABLE public.users ADD COLUMN IF NOT EXISTS peer_support_migrated BOOLEAN DEFAULT false;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS peer_support_migrated_at TIMESTAMPTZ;

