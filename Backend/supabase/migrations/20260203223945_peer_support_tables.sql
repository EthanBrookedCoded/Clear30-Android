-- 3. SMS TYPE TRACKING INDEX
--------------------------------------------------------------------------------

CREATE INDEX IF NOT EXISTS idx_sms_messages_accountability
    ON comms.sms_messages(user_id, type)
    WHERE sent_at IS NULL AND type IN ('slip_up', 'get_back', 'check_in');

--------------------------------------------------------------------------------
-- 4. DATABASE FUNCTIONS
--------------------------------------------------------------------------------

-- Function: Update peer conversation on message insert
CREATE OR REPLACE FUNCTION comms.update_peer_conversation()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO comms.peer_conversations (
        user_id,
        name,
        last_message_id,
        last_message_text,
        last_message_timestamp,
        last_message_outbound,
        updated_at
    )
    SELECT
        NEW.user_id,
        u.name,
        NEW.id,
        NEW.text,
        NEW.created_at,
        NEW.outbound,
        now()
    FROM public.users u
    WHERE u.id = NEW.user_id
    ON CONFLICT (user_id) DO UPDATE SET
        last_message_id = NEW.id,
        last_message_text = NEW.text,
        last_message_timestamp = NEW.created_at,
        last_message_outbound = NEW.outbound,
        unread_count = CASE
            WHEN NEW.outbound = true THEN comms.peer_conversations.unread_count + 1
            ELSE comms.peer_conversations.unread_count
        END,
        updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger for peer conversation updates
CREATE TRIGGER peer_message_insert_trigger
    AFTER INSERT ON comms.peer_messages
    FOR EACH ROW EXECUTE FUNCTION comms.update_peer_conversation();

-- Function: Queue push notification when outbound peer message is inserted
CREATE OR REPLACE FUNCTION comms.queue_peer_message_notification()
RETURNS TRIGGER AS $$
BEGIN
    -- Only queue notification for outbound messages (from admin/system)
    IF NEW.outbound = true THEN
        INSERT INTO comms.notifications (user_id, title, body, metadata, timestamp, status)
        VALUES (
            NEW.user_id,
            '💬 Julian',
            LEFT(NEW.text, 100),
            jsonb_build_object('type', 'peerMessage', 'message_id', NEW.id),
            now(),
            'pending'
        );

        -- Mark the message as notification queued
        UPDATE comms.peer_messages
        SET notification_sent = now()
        WHERE id = NEW.id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger for push notification queueing
CREATE TRIGGER peer_message_notification_trigger
    AFTER INSERT ON comms.peer_messages
    FOR EACH ROW EXECUTE FUNCTION comms.queue_peer_message_notification();

-- Function: Mark peer messages as read
CREATE OR REPLACE FUNCTION comms.mark_peer_messages_read(p_user_id TEXT)
RETURNS void AS $$
BEGIN
    UPDATE comms.peer_messages
    SET read_at = now()
    WHERE user_id = p_user_id AND outbound = true AND read_at IS NULL;

    UPDATE comms.peer_conversations
    SET unread_count = 0
    WHERE user_id = p_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

