CREATE OR REPLACE FUNCTION schools.get_all_schools_for_admin()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
SET search_path = schools, public
AS $$
BEGIN
  IF NOT schools.is_platform_admin() THEN
    RETURN '[]'::jsonb;
  END IF;
  RETURN (
    SELECT COALESCE(
      jsonb_agg(row_to_json(s) ORDER BY s.short_name),
      '[]'::jsonb
    )
    FROM schools.schools s
  );
END;
$$;


