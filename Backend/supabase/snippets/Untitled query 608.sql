CREATE TABLE IF NOT EXISTS schools.platform_admins (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_id    uuid UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
  email      text NOT NULL UNIQUE,
  name       text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE schools.platform_admins ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "deny_direct_access" ON schools.platform_admins;
CREATE POLICY "deny_direct_access" ON schools.platform_admins FOR ALL USING (false);


-- ─────────────────────────────────────────────────────────────
-- 2. is_platform_admin() helper function
-- ─────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION schools.is_platform_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = schools, public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM schools.platform_admins WHERE auth_id = auth.uid()
  )
$$;


